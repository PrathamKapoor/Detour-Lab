def validate_report_sources(
    *,
    scenario_id: str,
    run_ids: list[str],
    search_ids: list[str],
    experiment_ids: list[str],
) -> None:
    """Refuse a selection that cannot honestly be reported.

    Runs are mandatory: a packet with no analysed run would present invented
    results, which is exactly what the report must never do.
    """
    if not run_ids:
        raise ReportDataError(
            "at least one stored analysis run must be selected; a review packet cannot present "
            "results that were never computed",
            code="NO_SOURCE_RUN",
        )
    if len(set(run_ids)) != len(run_ids):
        raise ReportDataError(
            "the selected run ids contain duplicates",
            code="DUPLICATE_SELECTION",
            details={"run_ids": run_ids},
        )
    if len(set(search_ids)) != len(search_ids) or len(set(experiment_ids)) != len(experiment_ids):
        raise ReportDataError(
            "the selected search or experiment ids contain duplicates",
            code="DUPLICATE_SELECTION",
        )


def build_review_report(
    *,
    report_id: str,
    identity: ReportIdentity,
    scope: ReportScope,
    network: ReportNetwork,
    modifications: list[ReportModification],
    executive_summary: dict[str, Any],
    od_rows: list[ReportODRow],
    findings: list[ReportFinding],
    evidence_rows: list[ReportEvidenceRow],
    evidence_issues: list[ReportEvidenceIssue],
    alternative_plans: list[ReportAlternativePlan],
    experiments: list[ReportExperiment],
    robustness: RobustnessSummary | None,
    limitations: ReportLimitations,
    human_review: ReportSection12,
    section_availability: dict[str, SectionAvailability],
    selected_run_ids: list[str],
    selected_run_semantic_hashes: list[str],
    selected_run_input_hashes: list[str],
    selected_search_ids: list[str],
    selected_search_semantic_hashes: list[str],
    selected_experiment_ids: list[str],
    selected_experiment_semantic_hashes: list[str],
    selected_experiment_input_hashes: list[str],
) -> ReviewReport:
    """Assemble the report model. Every argument already comes from stored data."""
    reproducibility = ReportReproducibility(
        report_schema_version=REPORT_SCHEMA_VERSION,
        report_generator_version=REPORT_GENERATOR_VERSION,
        engine_version=ENGINE_VERSION,
        scenario_id=identity.scenario_id,
        scenario_revision=identity.scenario_revision,
        scenario_content_hash=identity.scenario_content_hash,
        base_graph_version_id=scope.graph_version_id,
        base_graph_hash=scope.graph_content_hash,
        rulepack_id=scope.rulepack_id,
        rulepack_version=scope.rulepack_version,
        rulepack_hash=scope.rulepack_hash,
        selected_run_ids=sorted(selected_run_ids),
        selected_run_semantic_hashes=sorted(selected_run_semantic_hashes),
        selected_run_input_hashes=sorted(selected_run_input_hashes),
        selected_search_ids=sorted(selected_search_ids),
        selected_search_semantic_hashes=sorted(selected_search_semantic_hashes),
        selected_experiment_ids=sorted(selected_experiment_ids),
        selected_experiment_semantic_hashes=sorted(selected_experiment_semantic_hashes),
        selected_experiment_input_hashes=sorted(selected_experiment_input_hashes),
        reproduction_steps=[
            f"Open scenario {identity.scenario_id!r} at revision {identity.scenario_revision} "
            f"(content hash {identity.scenario_content_hash}).",
            f"Confirm base graph version {scope.graph_version_id} "
            f"(content hash {scope.graph_content_hash}).",
            f"Confirm rulepack {scope.rulepack_id} version {scope.rulepack_version} "
            f"(content hash {scope.rulepack_hash}).",
            "Re-run the evaluation for each selected phase and profile at the recorded evaluation "
            "instant, and compare the resulting run semantic hashes with the selected run hashes.",
            "Re-execute each selected Failure Lab experiment from its recorded fault definitions "
            "and compare the experiment semantic hash.",
            "Regenerate this packet; the report semantic hash must reproduce exactly.",
        ],
    )
    report = ReviewReport(
        identity=identity,
        scope=scope,
        network=network,
        modifications=modifications,
        executive_summary=executive_summary,
        od_rows=od_rows,
        findings=findings,
        evidence_rows=evidence_rows,
        evidence_issues=evidence_issues,
        alternative_plans=alternative_plans,
        experiments=experiments,
        robustness=robustness.model_dump(mode="json") if robustness is not None else None,
        limitations=limitations,
        reproducibility=reproducibility,
        human_review=human_review,
        section_availability=section_availability,
    )
    # ``canonical_json_bytes`` is measured on the payload that carries the
    # placeholder value, then written back. That keeps the number well defined
    # (it cannot contain its own length) and still fully deterministic.
    return report.model_copy(
        update={
            "reproducibility": reproducibility.model_copy(
                update={"canonical_json_bytes": report.canonical_bytes()}
            )
        }
    )