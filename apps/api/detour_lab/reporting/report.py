"""Deterministic review-packet data model (Gate 6, G6-13/G6-14/G6-15).

Architecture
------------
Six separated stages, in this order:

1. **Authoritative data collection** - read stored runs, optimisation searches
   and failure experiments. Nothing is recomputed here and nothing is invented.
2. **Report data validation** - :func:`validate_report_sources` refuses
   malformed, missing or inconsistent selections before anything is written.
3. **Human-readable report model** - :class:`ReviewReport` is a deterministic,
   sorted, content-addressed structure. It is the single input to rendering.
4. **PDF rendering** - :mod:`detour_lab.reporting.pdf` lays the model out. It
   contains no accessibility, routing or evidence logic whatsoever.
5. **File delivery** - the API streams bytes with a server-generated filename.
6. **Reproducibility metadata** - ``semantic_hash`` over the report body.

Determinism contract
--------------------
The **semantic report payload** is deterministic: the same selections over the
same stored runs always serialise to identical bytes and therefore to an
identical ``semantic_hash``. Volatile metadata (``created_at``, durations,
report id, PDF hash) lives in a clearly separated ``runtime`` block that is
excluded from the fingerprint, exactly as the run manifest already does.

The renderer additionally runs ReportLab in invariant mode, which fixes the PDF
document id and creation date. Byte-identical PDFs are therefore produced for
identical payloads; that property is asserted by a test rather than assumed.

Honesty rules encoded in the model
----------------------------------
* No reviewer name, signature, institution or approval is ever present. The
  human-review section states explicitly that no review has been recorded unless
  one was supplied by the caller, and the API never supplies one.
* Costs appear only as stored (including ``null`` with ``cost_unknown``).
  Unknown cost is never rendered as zero.
* ``UNKNOWN`` and ``NOT_APPLICABLE`` are preserved as themselves.
* A section whose source analysis was not executed is emitted as
  ``unavailable`` with a reason - never as an empty table that reads as "none".
"""

