class ReviewReport(StrictModel):
    """The complete, deterministic report model."""

    schema_version: str = REPORT_SCHEMA_VERSION
    generator_version: str = REPORT_GENERATOR_VERSION
    engine_version: str = ENGINE_VERSION
    identity: ReportIdentity
    scope: ReportScope
    network: ReportNetwork
    modifications: list[ReportModification] = Field(default_factory=list)
    executive_summary: dict[str, Any] = Field(default_factory=dict)
    od_rows: list[ReportODRow] = Field(default_factory=list)
    findings: list[ReportFinding] = Field(default_factory=list)
    evidence_rows: list[ReportEvidenceRow] = Field(default_factory=list)
    evidence_issues: list[ReportEvidenceIssue] = Field(default_factory=list)
    alternative_plans: list[ReportAlternativePlan] = Field(default_factory=list)
    experiments: list[ReportExperiment] = Field(default_factory=list)
    robustness: dict[str, Any] | None = None
    limitations: ReportLimitations
    reproducibility: ReportReproducibility
    human_review: ReportSection12
    section_availability: dict[str, SectionAvailability] = Field(default_factory=dict)
    disclaimer: str = REPORT_DISCLAIMER
    not_certified_note: str = _NOT_CERTIFIED_NOTE

    def semantic_body(self) -> dict[str, Any]:
        """Payload whose hash is the report's semantic identity.

        ``identity.report_id`` is excluded, exactly as a run's ``run_id`` is
        excluded from its semantic hash. Two packets built from the same stored
        runs describe the same analysis and must share one semantic hash, while
        still carrying distinct identifiers.

        The identifier is still printed on the cover page, so a reader can tell
        two packets apart. The consequence is stated rather than hidden:
        regenerating **one stored report** reproduces byte-identical PDF bytes,
        while two separately generated reports of the same data differ in bytes
        because their covers name different identifiers. Both facts are asserted
        by tests rather than assumed.
        """
        payload = self.model_dump(mode="json")
        identity = dict(payload.get("identity") or {})
        identity.pop("report_id", None)
        payload["identity"] = identity
        return payload

    def semantic_hash(self) -> str:
        return semantic_hash(self.semantic_body())

    def canonical_bytes(self) -> int:
        return len(canonical_json(self.semantic_body()).encode("utf-8"))


