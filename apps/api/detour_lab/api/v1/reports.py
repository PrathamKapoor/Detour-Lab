"""Review-report HTTP surface (Gate 6, G6-13..G6-16).

Routes
------
``POST /api/v1/scenarios/{id}/reports``               build, render and store a packet
``GET  /api/v1/scenarios/{id}/reports``               stored packets for a scenario
``GET  /api/v1/reports/{report_id}``                   metadata + canonical payload
``GET  /api/v1/reports/{report_id}/manifest``          canonical JSON manifest (downloadable)
``GET  /api/v1/reports/{report_id}/document.pdf``      the rendered PDF

Safety controls applied at this boundary
---------------------------------------
* **No caller-supplied filename or path.** The download name is generated by the
  server from the stored report id, so a request cannot steer a write, read or
  content-disposition header anywhere.
* **No local paths in responses.** Only report, scenario and run identifiers are
  exposed.
* **Identity validation.** A caller may only select runs, searches and
  experiments that belong to the scenario in the path.
* **Bounded output.** The renderer refuses to emit more than
  :data:`~detour_lab.reporting.pdf.MAX_REPORT_PAGES` pages.
* **Regeneration is verification, not silent refresh.** Re-requesting a PDF
  re-renders the *stored payload*, so an old report keeps describing the runs it
  selected. Its stored content hash is returned so a client can confirm the
  bytes match what was originally generated.
"""

from __future__ import annotations

import json
import re

from fastapi import APIRouter, Depends, Response
from pydantic import BaseModel, ConfigDict, Field

from detour_lab.api.v1.routers import _error, get_repository
from detour_lab.persistence.repository import NotFoundError, Repository
from detour_lab.reporting.report import ReportDataError
from detour_lab.reporting.service import generate_report

router = APIRouter(prefix="/api/v1", tags=["reports"])

SAFE_IDENTIFIER_PATTERN = re.compile(r"^[A-Za-z0-9_\-]{1,64}$")


def _validate_id(identifier: str, name: str = "identifier") -> str:
    """Ensure identifier contains no path traversal or shell special characters."""
    if not isinstance(identifier, str) or not SAFE_IDENTIFIER_PATTERN.match(identifier):
        raise _error(
            400,
            "INVALID_IDENTIFIER",
            f"The {name} contains prohibited characters or exceeds maximum length.",
            {"parameter": name, "value": identifier},
        )
    return identifier


class CreateReportRequest(BaseModel):
    """Select stored artefacts to include. Unknown fields are refused."""

    model_config = ConfigDict(extra="forbid")
    run_ids: list[str] = Field(min_length=1, max_length=24)
    search_ids: list[str] = Field(default_factory=list, max_length=12)
    experiment_ids: list[str] = Field(default_factory=list, max_length=24)
    include_evidence_queue: bool = True
    queue_phase_ids: list[str] = Field(default_factory=list, max_length=6)


def _response_for(report) -> dict:
    return {
        "report": {
            "report_id": report.record_id,
            "semantic_hash": report.semantic_hash,
            "schema_version": report.payload.schema_version,
            "generator_version": report.payload.generator_version,
            "page_count": report.page_count,
            "pdf_bytes": len(report.pdf_bytes),
            "pdf_sha256": report.pdf_digest,
            "identity": report.payload.identity.model_dump(mode="json"),
            "reproducibility": report.payload.reproducibility.model_dump(mode="json"),
            "section_availability": {
                key: value.model_dump(mode="json")
                for key, value in report.payload.section_availability.items()
            },
            "disclaimer": report.payload.disclaimer,
            "runtime": report.runtime_block(),
        },
        "payload": report.payload.model_dump(mode="json"),
    }


@router.post("/scenarios/{scenario_id}/reports")
def create_report(
    scenario_id: str,
    payload: CreateReportRequest,
    repository: Repository = Depends(get_repository),
) -> dict:
    """Generate a review packet from specific stored runs and experiments."""
    _validate_id(scenario_id, "scenario_id")
    try:
        report = generate_report(
            repository=repository,
            scenario_id=scenario_id,
            run_ids=payload.run_ids,
            search_ids=payload.search_ids,
            experiment_ids=payload.experiment_ids,
            include_evidence_queue=payload.include_evidence_queue,
            queue_phase_ids=payload.queue_phase_ids or None,
        )
    except NotFoundError as exc:
        raise _error(404, "NOT_FOUND", str(exc)) from exc
    except ReportDataError as exc:
        raise _error(422, exc.code, str(exc), exc.details) from exc
    except Exception as exc:
        raise _error(
            500,
            "REPORT_GENERATION_FAILED",
            f"the review packet could not be generated: {type(exc).__name__}: {exc}",
            {"report_type": "pdf_review_packet"},
        ) from exc
    return _response_for(report)


@router.get("/scenarios/{scenario_id}/reports")
def list_reports(scenario_id: str, repository: Repository = Depends(get_repository)) -> dict:
    """Stored packets for a scenario, with the revision each one describes."""
    _validate_id(scenario_id, "scenario_id")
    try:
        records = repository.list_review_reports(scenario_id)
    except NotFoundError as exc:
        raise _error(404, "NOT_FOUND", str(exc)) from exc
    current_revision = repository.get_scenario(scenario_id).revision
    return {
        "scenario_id": scenario_id,
        "current_scenario_revision": current_revision,
        "reports": [
            {
                "report_id": record.report_id,
                "scenario_revision": record.scenario_revision,
                "describes_current_revision": record.scenario_revision == current_revision,
                "schema_version": record.schema_version,
                "generator_version": record.generator_version,
                "semantic_hash": record.semantic_hash,
                "pdf_sha256": record.pdf_sha256,
                "pdf_bytes": record.pdf_bytes,
                "pdf_page_count": record.pdf_page_count,
                "selected_run_ids": record.selected_run_ids,
                "selected_search_ids": record.selected_search_ids,
                "selected_experiment_ids": record.selected_experiment_ids,
                "created_at": record.created_at,
            }
            for record in records
        ],
        "report_count": len(records),
        "historical_note": (
            "A stored report describes the exact runs it selected, at the scenario revision recorded "
            "with it. It is never relabelled as representing a newer revision."
        ),
    }


@router.get("/reports/{report_id}")
def get_report(report_id: str, repository: Repository = Depends(get_repository)) -> dict:
    _validate_id(report_id, "report_id")
    try:
        record = repository.get_review_report(report_id)
    except NotFoundError as exc:
        raise _error(404, "NOT_FOUND", str(exc)) from exc
    current_revision = repository.get_scenario(record.scenario_id).revision
    return {
        "report_id": record.report_id,
        "scenario_id": record.scenario_id,
        "scenario_revision": record.scenario_revision,
        "current_scenario_revision": current_revision,
        "describes_current_revision": record.scenario_revision == current_revision,
        "schema_version": record.schema_version,
        "generator_version": record.generator_version,
        "semantic_hash": record.semantic_hash,
        "pdf_sha256": record.pdf_sha256,
        "pdf_bytes": record.pdf_bytes,
        "pdf_page_count": record.pdf_page_count,
        "selected_run_ids": record.selected_run_ids,
        "selected_search_ids": record.selected_search_ids,
        "selected_experiment_ids": record.selected_experiment_ids,
        "created_at": record.created_at,
        "payload": record.payload,
    }


@router.get("/reports/{report_id}/manifest")
def get_report_manifest(report_id: str, repository: Repository = Depends(get_repository)) -> Response:
    """The canonical report manifest, served verbatim as downloadable JSON."""
    _validate_id(report_id, "report_id")
    try:
        record = repository.get_review_report(report_id)
    except NotFoundError as exc:
        raise _error(404, "NOT_FOUND", str(exc)) from exc
    return Response(
        content=json.dumps(record.payload, indent=2, sort_keys=True, ensure_ascii=False),
        media_type="application/json",
        headers={
            "Content-Disposition": f'attachment; filename="detour-lab-review-{record.report_id}.json"',
            "X-Detour-Lab-Semantic-Hash": record.semantic_hash,
            "X-Detour-Lab-Scenario-Revision": str(record.scenario_revision),
        },
    )


@router.get("/reports/{report_id}/document.pdf")
def download_report_pdf(report_id: str, repository: Repository = Depends(get_repository)) -> Response:
    """Regenerate the PDF from the **stored payload** and stream it.

    Regeneration is deterministic, so the bytes match what was originally
    generated; ``X-Detour-Lab-Pdf-Sha256`` lets a client verify that without
    trusting the request.
    """
    _validate_id(report_id, "report_id")
    from detour_lab.reporting.pdf import pdf_sha256, render_report_pdf, rendered_page_count
    from detour_lab.reporting.report import ReviewReport

    try:
        record = repository.get_review_report(report_id)
    except NotFoundError as exc:
        raise _error(404, "NOT_FOUND", str(exc)) from exc
    try:
        payload = ReviewReport.model_validate(record.payload)
        pdf = render_report_pdf(payload)
    except Exception as exc:
        raise _error(
            500,
            "PDF_RENDER_FAILED",
            f"the stored packet could not be rendered: {type(exc).__name__}: {exc}",
            {"report_id": report_id},
        ) from exc
    digest = pdf_sha256(pdf)
    if digest != record.pdf_sha256:  # pragma: no cover - would be a renderer defect
        raise _error(
            500,
            "PDF_REGENERATION_MISMATCH",
            "re-rendering the stored packet did not reproduce the recorded content hash; refusing to "
            "serve a document that does not match its record",
            {"recorded_sha256": record.pdf_sha256, "recomputed_sha256": digest},
        )
    return Response(
        content=pdf,
        media_type="application/pdf",
        headers={
            "Content-Disposition": f'attachment; filename="detour-lab-review-{record.report_id}.pdf"',
            "Content-Length": str(len(pdf)),
            "X-Detour-Lab-Pdf-Sha256": digest,
            "X-Detour-Lab-Pdf-Pages": str(rendered_page_count(pdf)),
            "X-Detour-Lab-Semantic-Hash": record.semantic_hash,
            "X-Detour-Lab-Scenario-Revision": str(record.scenario_revision),
            "X-Detour-Lab-Not-Certified": "true",
        },
    )